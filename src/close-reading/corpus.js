export const CHAPTER_INDEX = (() => {
  const map = {}
  for (const book of BOOKS) for (const chapter of book.chapters) {
    map[chapter.id] = {
      book, chapter,
      text: chapter.paragraphs.join('\n')
    }
  }
  return map
})()

export function getChapter(chapterId) {
  return CHAPTER_INDEX[chapterId] || null
}

export function getVariantText(entry, variantId) {
  if (!variantId || variantId === 'base') return entry.text
  const variant = entry.chapter.variants?.find(v => v.id === variantId)
  return variant ? variant.paragraphs.join('\n') : entry.text
}

export function getVariantInfo(chapter, variantId) {
  if (!variantId || variantId === 'base') return { id: 'base', label: '通行本', note: '' }
  return chapter.variants?.find(v => v.id === variantId) || { id: 'base', label: '通行本', note: '' }
}

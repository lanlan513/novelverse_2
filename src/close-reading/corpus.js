function buildLongChapter(paragraphCount = 260) {
  const rand = mulberry32(20260918)
  const pick = arr => arr[Math.floor(rand() * arr.length)]
  const paragraphs = []
  for (let i = 0; i < paragraphCount; i++) {
    const sentences = 3 + Math.floor(rand() * 3)
    let text = ''
    for (let s = 0; s < sentences; s++) {
      text += pick(LONG_CLAUSES) + (rand() < 0.22 ? pick(LONG_SPEECH) : '')
      text += rand() < 0.5 ? '，' : '。'
    }
    paragraphs.push(`（其${i + 1}）` + text)
  }
  return paragraphs
}
